/***********************************************************************************************************************
 * Function:    AntiAlias
 *
 * Description: smooth transition across DCT block boundaries (every 18 coefficients)
 *
 * Inputs:      vector of dequantized coefficients, length = (nBfly+1) * 18
 *              number of "butterflies" to perform (one butterfly means one
 *                inter-block smoothing operation)
 *
 * Outputs:     updated coefficient vector x
 *
 * Return:      none
 *
 * Notes:       weighted average of opposite bands (pairwise) from the 8 samples
 *                before and after each block boundary
 *              nBlocks = (nonZeroBound + 7) / 18, since nZB is the first ZERO sample
 *                above which all other samples are also zero
 *              max gain per sample = 1.372
 *                MAX(i) (abs(csa[i][0]) + abs(csa[i][1]))
 *              bits gained = 0
 *              assume at least 1 guard bit in x[] to avoid overflow
 *                (should be guaranteed from dequant, and max gain from stproc * max
 *                 gain from AntiAlias < 2.0)
 **********************************************************************************************************************/
// a little bit faster in RAM (< 1 ms per block)
/* __attribute__ ((section (".data"))) */
void MP3Decoder::AntiAlias(int32_t* x, int32_t nBfly)
{
  for (int32_t k = nBfly; k > 0; --k)
  {
    x += 18;
#pragma GCC unroll 8
    for (int32_t i = 0; i < 8; ++i)
    {
      const int32_t a0 = x[-1 - i];
      const int32_t c0 = static_cast<int32_t>(csa[i][0]);
      const int32_t b0 = x[i];
      const int32_t c1 = static_cast<int32_t>(csa[i][1]);
      x[-1 - i] = shl32(MULSHIFT32(c0, a0) - MULSHIFT32(c1, b0), 1);
      x[i] = shl32(MULSHIFT32(c0, b0) + MULSHIFT32(c1, a0), 1);
    }
  }
}

/***********************************************************************************************************************
 * Function:    WinPrevious
 *
 * Description: apply specified window to second half of previous IMDCT (overlap part)
 *
 * Inputs:      vector of 9 coefficients (xPrev)
 *
 * Outputs:     18 windowed output coefficients (gain 1 integer bit)
 *              window type (0, 1, 2, 3)
 *
 * Return:      none
 *
 * Notes:       produces 9 output samples from 18 input samples via symmetry
 *              all blocks gain at least 1 guard bit via window (long blocks get extra
 *                sign bit, short blocks can have one addition but max gain < 1.0)
 **********************************************************************************************************************/
void MP3Decoder::WinPrevious(int32_t* xPrev, int32_t* xPrevWin, int32_t btPrev)
{
  btPrev &= 0x03;
  if (btPrev == 2)
  {
    const uint32_t* wpLo = imdctWin[2];
    xPrevWin[0] = MULSHIFT32(static_cast<int32_t>(wpLo[6]), xPrev[2]) + MULSHIFT32(static_cast<int32_t>(wpLo[0]), xPrev[6]);
    xPrevWin[1] = MULSHIFT32(static_cast<int32_t>(wpLo[7]), xPrev[1]) + MULSHIFT32(static_cast<int32_t>(wpLo[1]), xPrev[7]);
    xPrevWin[2] = MULSHIFT32(static_cast<int32_t>(wpLo[8]), xPrev[0]) + MULSHIFT32(static_cast<int32_t>(wpLo[2]), xPrev[8]);
    xPrevWin[3] = MULSHIFT32(static_cast<int32_t>(wpLo[9]), xPrev[0]) + MULSHIFT32(static_cast<int32_t>(wpLo[3]), xPrev[8]);
    xPrevWin[4] = MULSHIFT32(static_cast<int32_t>(wpLo[10]), xPrev[1]) + MULSHIFT32(static_cast<int32_t>(wpLo[4]), xPrev[7]);
    xPrevWin[5] = MULSHIFT32(static_cast<int32_t>(wpLo[11]), xPrev[2]) + MULSHIFT32(static_cast<int32_t>(wpLo[5]), xPrev[6]);
    xPrevWin[6] = MULSHIFT32(static_cast<int32_t>(wpLo[6]), xPrev[5]);
    xPrevWin[7] = MULSHIFT32(static_cast<int32_t>(wpLo[7]), xPrev[4]);
    xPrevWin[8] = MULSHIFT32(static_cast<int32_t>(wpLo[8]), xPrev[3]);
    xPrevWin[9] = MULSHIFT32(static_cast<int32_t>(wpLo[9]), xPrev[3]);
    xPrevWin[10] = MULSHIFT32(static_cast<int32_t>(wpLo[10]), xPrev[4]);
    xPrevWin[11] = MULSHIFT32(static_cast<int32_t>(wpLo[11]), xPrev[5]);
    xPrevWin[12] = xPrevWin[13] = xPrevWin[14] = xPrevWin[15] = xPrevWin[16] = xPrevWin[17] = 0;
  }
  else
  {
    const int32_t* xp = xPrev;
    const uint32_t* wpLo = imdctWin[btPrev] + 18;
    const uint32_t* wpHi = wpLo + 17;
    int32_t* xpwLo = xPrevWin;
    int32_t* xpwHi = xPrevWin + 17;
    for (int32_t i = 9; i > 0; i--)
    {
      const int32_t x = *xp++;
      const int32_t wLo = static_cast<int32_t>(*wpLo++);
      const int32_t wHi = static_cast<int32_t>(*wpHi--);
      *xpwLo++ = MULSHIFT32(wLo, x);
      *xpwHi-- = MULSHIFT32(wHi, x);
    }
  }
}

/***********************************************************************************************************************
 * Function:    FreqInvertRescale
 *
 * Description: do frequency inversion (odd samples of odd blocks) and rescale
 *                if necessary (extra guard bits added before IMDCT)
 *
 * Inputs:      output vector y (18 new samples, spaced NBANDS apart)
 *              previous sample vector xPrev (9 samples)
 *              index of current block
 *              number of extra shifts added before IMDCT (usually 0)
 *
 * Outputs:     inverted and rescaled (as necessary) outputs
 *              rescaled (as necessary) previous samples
 *
 * Return:      updated mOut (from new outputs y)
 **********************************************************************************************************************/
int32_t MP3Decoder::FreqInvertRescale(int32_t* y, int32_t* xPrev, int32_t blockIdx, int32_t es)
{
  uint32_t mOut = 0;
  if (es == 0)
  {
    if (blockIdx & 0x01)
    {
      for (int32_t i = 0; i < 9; i++)
      {
        mOut |= uabs32(*y);
        y += m_NBANDS;
        *y = static_cast<int32_t>(0u - static_cast<uint32_t>(*y));
        mOut |= uabs32(*y);
        y += m_NBANDS;
      }
    }
    else
    {
      for (int32_t i = 0; i < 9; i++)
      {
        mOut |= uabs32(*y);
        y += m_NBANDS;
        mOut |= uabs32(*y);
        y += m_NBANDS;
      }
    }
    return static_cast<int32_t>(mOut);
  }

  const int32_t clipBits = 31 - es;
  if (blockIdx & 0x01)
  {
    for (int32_t i = 0; i < 9; i++)
    {
      int32_t d = clip2n(*y, clipBits);
      *y = shl32(d, es);
      mOut |= uabs32(*y);
      y += m_NBANDS;

      d = clip2n(static_cast<int32_t>(0u - static_cast<uint32_t>(*y)), clipBits);
      *y = shl32(d, es);
      mOut |= uabs32(*y);
      y += m_NBANDS;

      d = clip2n(*xPrev, clipBits);
      *xPrev++ = shl32(d, es);
    }
  }
  else
  {
    for (int32_t i = 0; i < 9; i++)
    {
      int32_t d = clip2n(*y, clipBits);
      *y = shl32(d, es);
      mOut |= uabs32(*y);
      y += m_NBANDS;

      d = clip2n(*y, clipBits);
      *y = shl32(d, es);
      mOut |= uabs32(*y);
      y += m_NBANDS;

      d = clip2n(*xPrev, clipBits);
      *xPrev++ = shl32(d, es);
    }
  }
  return static_cast<int32_t>(mOut);
}

/* require at least 3 guard bits in x[] to ensure no overflow */
void MP3Decoder::idct9(int32_t* x)
{
  int32_t a1, a2, a3, a4, a5, a6, a7, a8, a9;
  int32_t a10, a11, a12, a13, a14, a15, a16, a17, a18;
  int32_t a19, a20, a21, a22, a23, a24, a25, a26, a27;
  int32_t m1, m3, m5, m6, m7, m8, m9, m10, m11, m12;
  int32_t x0, x1, x2, x3, x4, x5, x6, x7, x8;

  x0 = x[0];
  x1 = x[1];
  x2 = x[2];
  x3 = x[3];
  x4 = x[4];
  x5 = x[5];
  x6 = x[6];
  x7 = x[7];
  x8 = x[8];

  a1 = x0 - x6;
  a2 = x1 - x5;
  a3 = x1 + x5;
  a4 = x2 - x4;
  a5 = x2 + x4;
  a6 = x2 + x8;
  a7 = x1 + x7;

  a8 = a6 - a5;  /* x[8] - x[4] */
  a9 = a3 - a7;  /* x[5] - x[7] */
  a10 = a2 - x7; /* x[1] - x[5] - x[7] */
  a11 = a4 - x8; /* x[2] - x[4] - x[8] */

  m1 = shl32(MULSHIFT32(c9_0, x3), 1);
  m3 = shl32(MULSHIFT32(c9_0, a10), 1);
  m5 = shl32(MULSHIFT32(c9_1, a5), 1);
  m6 = shl32(MULSHIFT32(c9_2, a6), 1);
  m7 = shl32(MULSHIFT32(c9_1, a8), 1);
  m8 = shl32(MULSHIFT32(c9_2, a5), 1);
  m9 = shl32(MULSHIFT32(c9_3, a9), 1);
  m10 = shl32(MULSHIFT32(c9_4, a7), 1);
  m11 = shl32(MULSHIFT32(c9_3, a3), 1);
  m12 = shl32(MULSHIFT32(c9_4, a9), 1);

  a12 = x0 + (x6 >> 1);
  a13 = a12 + m1;
  a14 = a12 - m1;
  a15 = a1 + (a11 >> 1);
  a16 = m5 + m6;
  a17 = m7 - m8;
  a18 = a16 + a17;
  a19 = m9 + m10;
  a20 = m11 - m12;

  a21 = a20 - a19;
  a22 = a13 + a16;
  a23 = a14 + a16;
  a24 = a14 + a17;
  a25 = a13 + a17;
  a26 = a14 - a18;
  a27 = a13 - a18;

  x[0] = a22 + a19;
  x[1] = a15 + m3;
  x[2] = a24 + a20;
  x[3] = a26 - a21;
  x[4] = a1 - a11;
  x[5] = a27 + a21;
  x[6] = a25 - a20;
  x[7] = a15 - m3;
  x[8] = a23 - a19;
}

/***********************************************************************************************************************
 * Function:    IMDCT36
 *
 * Description: 36-point modified DCT, with windowing and overlap-add (50% overlap)
 *
 * Inputs:      vector of 18 coefficients (N/2 inputs produces N outputs, by symmetry)
 *              overlap part of last IMDCT (9 samples - see output comments)
 *              window type (0,1,2,3) of current and previous block
 *              current block index (for deciding whether to do frequency inversion)
 *              number of guard bits in input vector
 *
 * Outputs:     18 output samples, after windowing and overlap-add with last frame
 *              second half of (unwindowed) 36-point IMDCT - save for next time
 *                only save 9 xPrev samples, using symmetry (see WinPrevious())
 *
 * Notes:       this is Ken's hyper-fast algorithm, including symmetric sin window
 *                optimization, if applicable
 *              total number of multiplies, general case:
 *                2*10 (idct9) + 9 (last stage imdct) + 36 (for windowing) = 65
 *              total number of multiplies, btCurr == 0 && btPrev == 0:
 *                2*10 (idct9) + 9 (last stage imdct) + 18 (for windowing) = 47
 *
 *              blockType == 0 is by far the most common case, so it should be
 *                possible to use the fast path most of the time
 *              this is the fastest known algorithm for performing
 *                long IMDCT + windowing + overlap-add in MP3
 *
 * Return:      mOut (OR of abs(y) for all y calculated here)
 **********************************************************************************************************************/
// barely faster in RAM
int32_t MP3Decoder::IMDCT36(int32_t* xCurr, int32_t* xPrev, int32_t* y, int32_t btCurr, int32_t btPrev, int32_t blockIdx, int32_t gb)
{
  int32_t i, es, xBuf[18], xPrevWin[18];
  int32_t acc1 = 0, acc2 = 0, s, d, t;
  int32_t xo, xe, c, yLo, yHi;
  uint32_t mOut = 0;
  const uint32_t* wp;

  es = (gb < 7) ? (7 - gb) : 0;

  uint32_t prevMask = 0;
  for (i = 0; i < 9; i++)
  {
    prevMask |= uabs32(xPrev[i]);
  }
  const int32_t gbPrev = CLZ(prevMask) - 1;
  if (gbPrev < 3)
  {
    const int32_t esPrev = 3 - gbPrev;
    if (esPrev > es)
    {
      es = esPrev;
    }
  }
  if (es > 31)
  {
    es = 31;
  }

  if (es > 0)
  {
    for (i = 8; i >= 0; i--)
    {
      acc1 = (xCurr[2 * i + 1] >> es) - acc1;
      acc2 = acc1 - acc2;
      acc1 = (xCurr[2 * i + 0] >> es) - acc1;
      xBuf[i + 9] = acc2;
      xBuf[i + 0] = acc1;
      xPrev[i] >>= es;
    }
  }
  else
  {
    for (i = 8; i >= 0; i--)
    {
      acc1 = xCurr[2 * i + 1] - acc1;
      acc2 = acc1 - acc2;
      acc1 = xCurr[2 * i + 0] - acc1;
      xBuf[i + 9] = acc2;
      xBuf[i + 0] = acc1;
    }
  }
  xBuf[9] >>= 1;
  xBuf[0] >>= 1;

  idct9(xBuf + 0);
  idct9(xBuf + 9);

  if (btPrev == 0 && btCurr == 0)
  {
    wp = fastWin36;
    for (i = 0; i < 9; i++)
    {
      c = static_cast<int32_t>(c18[8 - i]);
      xo = xBuf[17 - i];
      xe = xBuf[8 - i];
      xo = MULSHIFT32(c, xo);
      xe >>= 2;

      s = -xPrev[i];
      d = -(xe - xo);
      xPrev[i] = xe + xo;
      t = s - d;

      yLo = d + shl32(MULSHIFT32(t, static_cast<int32_t>(*wp++)), 2);
      yHi = s + shl32(MULSHIFT32(t, static_cast<int32_t>(*wp++)), 2);
      y[i * m_NBANDS] = yLo;
      y[(17 - i) * m_NBANDS] = yHi;
      mOut |= uabs32(yLo);
      mOut |= uabs32(yHi);
    }
  }
  else
  {
    WinPrevious(xPrev, xPrevWin, btPrev);
    wp = imdctWin[btCurr & 0x03];
    for (i = 0; i < 9; i++)
    {
      c = static_cast<int32_t>(c18[8 - i]);
      xo = xBuf[17 - i];
      xe = xBuf[8 - i];
      xo = MULSHIFT32(c, xo);
      xe >>= 2;

      d = xe - xo;
      xPrev[i] = xe + xo;

      yLo = shl32(xPrevWin[i] + MULSHIFT32(d, static_cast<int32_t>(wp[i])), 2);
      yHi = shl32(xPrevWin[17 - i] + MULSHIFT32(d, static_cast<int32_t>(wp[17 - i])), 2);
      y[i * m_NBANDS] = yLo;
      y[(17 - i) * m_NBANDS] = yHi;
      mOut |= uabs32(yLo);
      mOut |= uabs32(yHi);
    }
  }

  if (es == 0 && (blockIdx & 0x01) == 0)
  {
    return static_cast<int32_t>(mOut);
  }
  return FreqInvertRescale(y, xPrev, blockIdx, es);
}

/* 12-point inverse DCT, used in IMDCT12x3()
 * 4 input guard bits will ensure no overflow
 */
void MP3Decoder::imdct12(int32_t* x, int32_t* out)
{
  int32_t a0, a1, a2;
  int32_t x0 = *x;
  x += 3;
  int32_t x1 = *x;
  x += 3;
  int32_t x2 = *x;
  x += 3;
  int32_t x3 = *x;
  x += 3;
  int32_t x4 = *x;
  x += 3;
  int32_t x5 = *x;

  x4 -= x5;
  x3 -= x4;
  x2 -= x3;
  x3 -= x5;
  x1 -= x2;
  x0 -= x1;
  x1 -= x3;
  x0 >>= 1;
  x1 >>= 1;

  a0 = shl32(MULSHIFT32(c3_0, x2), 1);
  a1 = x0 + (x4 >> 1);
  a2 = x0 - x4;
  x0 = a1 + a0;
  x2 = a2;
  x4 = a1 - a0;

  a0 = shl32(MULSHIFT32(c3_0, x3), 1);
  a1 = x1 + (x5 >> 1);
  a2 = x1 - x5;

  x1 = shl32(MULSHIFT32(c6[0], a1 + a0), 2);
  x3 = shl32(MULSHIFT32(c6[1], a2), 2);
  x5 = shl32(MULSHIFT32(c6[2], a1 - a0), 2);

  out[0] = x0 + x1;
  out[1] = x2 + x3;
  out[2] = x4 + x5;
  out[3] = x4 - x5;
  out[4] = x2 - x3;
  out[5] = x0 - x1;
}

/***********************************************************************************************************************
 * Function:    IMDCT12x3
 *
 * Description: three 12-point modified DCT's for short blocks, with windowing,
 *                short block concatenation, and overlap-add
 *
 * Inputs:      3 interleaved vectors of 6 samples each
 *                (block0[0], block1[0], block2[0], block0[1], block1[1]....)
 *              overlap part of last IMDCT (9 samples - see output comments)
 *              window type (0,1,2,3) of previous block
 *              current block index (for deciding whether to do frequency inversion)
 *              number of guard bits in input vector
 *
 * Outputs:     updated sample vector x, net gain of 1 integer bit
 *              second half of (unwindowed) IMDCT's - save for next time
 *                only save 9 xPrev samples, using symmetry (see WinPrevious())
 *
 * Return:      mOut (OR of abs(y) for all y calculated here)
 **********************************************************************************************************************/
// barely faster in RAM
int32_t MP3Decoder::IMDCT12x3(int32_t* xCurr, int32_t* xPrev, int32_t* y, int32_t btPrev, int32_t blockIdx, int32_t gb)
{
  int32_t i, es, yLo, xBuf[18], xPrevWin[18];
  uint32_t mOut = 0;

  es = (gb < 7) ? (7 - gb) : 0;

  uint32_t prevMask = 0;
  for (i = 0; i < 9; i++)
  {
    prevMask |= uabs32(xPrev[i]);
  }
  const int32_t gbPrev = CLZ(prevMask) - 1;
  if (gbPrev < 3)
  {
    const int32_t esPrev = 3 - gbPrev;
    if (esPrev > es)
    {
      es = esPrev;
    }
  }
  if (es > 31)
  {
    es = 31;
  }

  if (es > 0)
  {
    for (i = 0; i < 9; i++)
    {
      xCurr[2 * i + 0] >>= es;
      xCurr[2 * i + 1] >>= es;
      xPrev[i] >>= es;
    }
  }

  imdct12(xCurr + 0, xBuf + 0);
  imdct12(xCurr + 1, xBuf + 6);
  imdct12(xCurr + 2, xBuf + 12);

  WinPrevious(xPrev, xPrevWin, btPrev);

  const uint32_t* wp = imdctWin[2];
  for (i = 0; i < 3; i++)
  {
    yLo = shl32(xPrevWin[0 + i], 2);
    mOut |= uabs32(yLo);
    y[(0 + i) * m_NBANDS] = yLo;

    yLo = shl32(xPrevWin[3 + i], 2);
    mOut |= uabs32(yLo);
    y[(3 + i) * m_NBANDS] = yLo;

    yLo = shl32(xPrevWin[6 + i], 2) + MULSHIFT32(static_cast<int32_t>(wp[0 + i]), xBuf[3 + i]);
    mOut |= uabs32(yLo);
    y[(6 + i) * m_NBANDS] = yLo;

    yLo = shl32(xPrevWin[9 + i], 2) + MULSHIFT32(static_cast<int32_t>(wp[3 + i]), xBuf[5 - i]);
    mOut |= uabs32(yLo);
    y[(9 + i) * m_NBANDS] = yLo;

    yLo = shl32(xPrevWin[12 + i], 2) +
        (MULSHIFT32(static_cast<int32_t>(wp[6 + i]), xBuf[2 - i]) +
         MULSHIFT32(static_cast<int32_t>(wp[0 + i]), xBuf[9 + i]));
    mOut |= uabs32(yLo);
    y[(12 + i) * m_NBANDS] = yLo;

    yLo = shl32(xPrevWin[15 + i], 2) +
        (MULSHIFT32(static_cast<int32_t>(wp[9 + i]), xBuf[0 + i]) +
         MULSHIFT32(static_cast<int32_t>(wp[3 + i]), xBuf[11 - i]));
    mOut |= uabs32(yLo);
    y[(15 + i) * m_NBANDS] = yLo;
  }

  for (i = 0; i < 3; i++)
    xPrev[i] = xBuf[6 + i] >> 2;
  for (i = 0; i < 6; i++)
    xPrev[3 + i] = xBuf[12 + i] >> 2;

  if (es == 0 && (blockIdx & 0x01) == 0)
  {
    return static_cast<int32_t>(mOut);
  }
  return FreqInvertRescale(y, xPrev, blockIdx, es);
}

/***********************************************************************************************************************
 * Function:    HybridTransform
 *
 * Description: IMDCT's, windowing, and overlap-add on long/short/mixed blocks
 *
 * Inputs:      vector of input coefficients, length = nBlocksTotal * 18)
 *              vector of overlap samples from last time, length = nBlocksPrev * 9)
 *              buffer for output samples, length = MAXNSAMP
 *              SideInfoSub struct for this granule/channel
 *              BlockCount struct with necessary info
 *                number of non-zero input and overlap blocks
 *                number of long blocks in input vector (rest assumed to be short blocks)
 *                number of blocks which use long window (type) 0 in case of mixed block
 *                  (bc->currWinSwitch, 0 for non-mixed blocks)
 *
 * Outputs:     transformed, windowed, and overlapped sample buffer
 *              does frequency inversion on odd blocks
 *              updated buffer of samples for overlap
 *
 * Return:      number of non-zero IMDCT blocks calculated in this call
 *                (including overlap-add)
 **********************************************************************************************************************/
int32_t MP3Decoder::HybridTransform(int32_t* xCurr, int32_t* xPrev, int32_t y[m_BLOCK_SIZE][m_NBANDS], SideInfoSub_t* sis, BlockCount_t* bc)
{
  int32_t i, j, nBlocksOut, currWinIdx, prevWinIdx, nonZero, xp;
  int32_t xPrevWin[18];
  uint32_t mOut = 0;

  assert(bc->nBlocksLong <= m_NBANDS);
  assert(bc->nBlocksTotal <= m_NBANDS);
  assert(bc->nBlocksPrev <= m_NBANDS);

  for (i = 0; i < bc->nBlocksLong; i++)
  {
    currWinIdx = sis->blockType;
    if (sis->mixedBlock && i < bc->currWinSwitch)
      currWinIdx = 0;

    prevWinIdx = bc->prevType;
    if (i < bc->prevWinSwitch)
      prevWinIdx = 0;

    mOut |= static_cast<uint32_t>(IMDCT36(xCurr, xPrev, &(y[0][i]), currWinIdx, prevWinIdx, i, bc->gbIn));
    xCurr += 18;
    xPrev += 9;
  }

  for (; i < bc->nBlocksTotal; i++)
  {
    assert(sis->blockType == 2);
    prevWinIdx = bc->prevType;
    if (i < bc->prevWinSwitch)
      prevWinIdx = 0;

    mOut |= static_cast<uint32_t>(IMDCT12x3(xCurr, xPrev, &(y[0][i]), prevWinIdx, i, bc->gbIn));
    xCurr += 18;
    xPrev += 9;
  }
  nBlocksOut = i;

  for (; i < bc->nBlocksPrev; i++)
  {
    prevWinIdx = bc->prevType;
    if (i < bc->prevWinSwitch)
      prevWinIdx = 0;
    WinPrevious(xPrev, xPrevWin, prevWinIdx);

    nonZero = 0;
    const bool oddBlock = (i & 0x01) != 0;
    for (j = 0; j < 9; j++)
    {
      xp = shl32(xPrevWin[2 * j + 0], 2);
      nonZero |= xp;
      y[2 * j + 0][i] = xp;
      mOut |= uabs32(xp);

      xp = shl32(xPrevWin[2 * j + 1], 2);
      if (oddBlock)
      {
        xp = static_cast<int32_t>(0u - static_cast<uint32_t>(xp));
      }
      nonZero |= xp;
      y[2 * j + 1][i] = xp;
      mOut |= uabs32(xp);

      xPrev[j] = 0;
    }
    xPrev += 9;
    if (nonZero)
      nBlocksOut = i;
  }

  if (i < m_NBANDS)
  {
    const size_t zeroBytes = static_cast<size_t>(m_NBANDS - i) * sizeof(int32_t);
    for (j = 0; j < m_BLOCK_SIZE; j++)
    {
      memset(&y[j][i], 0, zeroBytes);
    }
  }

  int32_t gbOut = CLZ(mOut) - 1;
  bc->gbOut = (gbOut < 0) ? 0 : gbOut;
  return nBlocksOut;
}

/***********************************************************************************************************************
 * Function:    IMDCT
 *
 * Description: do alias reduction, inverse MDCT, overlap-add, and frequency inversion
 *
 * Inputs:      MP3DecInfo structure filled by UnpackFrameHeader(), UnpackSideInfo(),
 *                UnpackScaleFactors(), and DecodeHuffman() (for this granule, channel)
 *                includes PCM samples in overBuf (from last call to IMDCT) for OLA
 *              index of current granule and channel
 *
 * Outputs:     PCM samples in outBuf, for input to subband transform
 *              PCM samples in overBuf, for OLA next time
 *              updated hi->nonZeroBound index for this channel
 *
 * Return:      0 on success,  -1 if null input pointers
 **********************************************************************************************************************/
// a bit faster in RAM
/*__attribute__ ((section (".data")))*/
int32_t MP3Decoder::IMDCT(int32_t gr, int32_t ch)
{
  if (!m_HuffmanInfo || !m_IMDCTInfo)
    return -1;

  int32_t nBfly, blockCutoff;
  BlockCount_t bc;

  blockCutoff = m_SFBandTable.l[(m_MPEGVersion == MPEG1 ? 8 : 6)] / 18;
  if (m_SideInfoSub[gr][ch].blockType != 2)
  {
    int32_t x = (m_HuffmanInfo->nonZeroBound[ch] + 7) / 18 + 1;
    bc.nBlocksLong = (x < 32 ? x : 32);
    nBfly = bc.nBlocksLong - 1;
  }
  else if (m_SideInfoSub[gr][ch].blockType == 2 && m_SideInfoSub[gr][ch].mixedBlock)
  {
    bc.nBlocksLong = blockCutoff;
    nBfly = bc.nBlocksLong - 1;
  }
  else
  {
    bc.nBlocksLong = 0;
    nBfly = 0;
  }

  if (nBfly < 0)
    nBfly = 0;

  AntiAlias(m_HuffmanInfo->huffDecBuf[ch], nBfly);
  int32_t x = m_HuffmanInfo->nonZeroBound[ch];
  int32_t y = nBfly * 18 + 8;
  m_HuffmanInfo->nonZeroBound[ch] = (x > y ? x : y);
  if (m_HuffmanInfo->nonZeroBound[ch] > m_MAX_NSAMP)
    m_HuffmanInfo->nonZeroBound[ch] = m_MAX_NSAMP;

  bc.nBlocksTotal = (m_HuffmanInfo->nonZeroBound[ch] + 17) / 18;
  bc.nBlocksPrev = m_IMDCTInfo->numPrevIMDCT[ch];
  bc.prevType = m_IMDCTInfo->prevType[ch];
  bc.prevWinSwitch = m_IMDCTInfo->prevWinSwitch[ch];
  bc.currWinSwitch = (m_SideInfoSub[gr][ch].mixedBlock ? blockCutoff : 0);
  bc.gbIn = m_HuffmanInfo->gb[ch];

  m_IMDCTInfo->numPrevIMDCT[ch] = HybridTransform(m_HuffmanInfo->huffDecBuf[ch], m_IMDCTInfo->overBuf[ch],
                                                  m_IMDCTInfo->outBuf[ch], &m_SideInfoSub[gr][ch], &bc);
  m_IMDCTInfo->prevType[ch] = m_SideInfoSub[gr][ch].blockType;
  m_IMDCTInfo->prevWinSwitch[ch] = bc.currWinSwitch;
  m_IMDCTInfo->gb[ch] = bc.gbOut;

  if (m_IMDCTInfo->numPrevIMDCT[ch] > m_NBANDS)
    m_IMDCTInfo->numPrevIMDCT[ch] = m_NBANDS;

  return 0;
}

